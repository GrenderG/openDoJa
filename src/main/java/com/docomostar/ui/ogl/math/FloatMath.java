package com.docomostar.ui.ogl.math;

public final class FloatMath {
    private FloatMath() { }
    public static float sin(float value) { return com.nttdocomo.ui.ogl.math.FloatMath.sin(value); }
    public static float cos(float value) { return com.nttdocomo.ui.ogl.math.FloatMath.cos(value); }
    public static float tan(float value) { return com.nttdocomo.ui.ogl.math.FloatMath.tan(value); }
    public static float sqrt(float value) { return com.nttdocomo.ui.ogl.math.FloatMath.sqrt(value); }
    public static float atan(float value) { return com.nttdocomo.ui.ogl.math.FloatMath.atan(value); }
    public static float atan2(float y, float x) { return com.nttdocomo.ui.ogl.math.FloatMath.atan2(y, x); }
}
