package com.docomostar.opt.ui.j3d;

/** Fixed-point arithmetic shared with the DoJa implementation. */
public final class Math {
    private Math() { }
    public static int sqrt(int value) { return com.nttdocomo.opt.ui.j3d.Math.sqrt(value); }
    public static int sin(int angle) { return com.nttdocomo.opt.ui.j3d.Math.sin(angle); }
    public static int cos(int angle) { return com.nttdocomo.opt.ui.j3d.Math.cos(angle); }
    public static int atan2(int y, int x) { return com.nttdocomo.opt.ui.j3d.Math.atan2(y, x); }
}
